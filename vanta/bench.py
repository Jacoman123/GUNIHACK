"""Benchmark: every strategy on every scenario over many seeds."""

from __future__ import annotations

import statistics
import time
from concurrent.futures import ProcessPoolExecutor
from pathlib import Path

from .scenarios import SCENARIOS, Scenario
from .sim import Simulation
from .strategies import STRATEGIES


def run_one(args: tuple[Scenario, str, int]) -> dict:
    sc, strategy, seed = args
    m = Simulation(sc, strategy, seed).run().metrics()
    m.update(scenario=sc.name, strategy=strategy, seed=seed, loss_setting=sc.loss)
    return m


def _fmt_t(v: float | None) -> str:
    return "—" if v is None else f"{v / 60:.1f} min"


def _summarise(rows: list[dict]) -> dict:
    done = [r for r in rows if r["reported_t"] is not None]
    covered = [r for r in rows if r["covered_t"] is not None]
    return {
        "n": len(rows),
        "done": len(done),
        "covered_med": statistics.median(r["covered_t"] for r in covered) if len(covered) == len(rows) else None,
        "reported_med": statistics.median(r["reported_t"] for r in done) if len(done) == len(rows) else None,
        "true_pct": statistics.mean(r["true_pct"] for r in rows),
        "overlap": statistics.mean(r["overlap_pct"] for r in rows),
        "idle": statistics.mean(r["idle_min"] for r in rows),
    }


def benchmark(seeds: int = 10, jobs: int | None = None, out: Path | None = None) -> str:
    strategies = list(STRATEGIES)
    tasks = [(sc, st, seed) for sc in SCENARIOS.values() for st in strategies
             for seed in range(1, seeds + 1)]
    losses = [0.0, 0.25, 0.5, 0.75, 0.9]
    nominal = SCENARIOS["nominal"]
    sweep = [(nominal.with_(name=f"loss{int(p * 100)}", loss=p), st, seed)
             for p in losses for st in ("vanta", "central") for seed in range(1, seeds + 1)]

    t0 = time.time()
    with ProcessPoolExecutor(max_workers=jobs) as ex:
        rows = list(ex.map(run_one, tasks + sweep, chunksize=2))
    wall = time.time() - t0

    main = [r for r in rows if r["scenario"] in SCENARIOS]
    lines = [
        "# Vanta benchmark",
        "",
        f"{len(SCENARIOS)} scenarios x {len(strategies)} strategies x {seeds} seeds "
        f"(10 drones, 1.28 x 0.96 km area, 3072 cells, 8 survivors). "
        f"Generated by `python -m vanta bench --seeds {seeds}` in {wall:.0f} s.",
        "",
        "* **Searched**: median time until every cell has been searched by some drone.",
        "* **Mission complete**: median time until the base station knows every cell is searched "
        "and where every survivor is. A dash means some seeds never got there in 40 minutes.",
        "* **Wasted**: cells searched again only because the drone didn't know someone had "
        "already done them, as % of the area.",
        "* **Idle**: drone-minutes spent alive but not searching while work remained.",
        "",
        "| Scenario | Strategy | Searched | Mission complete | Completed | Area searched | Wasted | Idle |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for name, sc in SCENARIOS.items():
        for st in strategies:
            s = _summarise([r for r in main if r["scenario"] == name and r["strategy"] == st])
            label = STRATEGIES[st].label
            if st == "vanta":
                label = f"**{label}**"
            lines.append(
                f"| {sc.title} | {label} | {_fmt_t(s['covered_med'])} | {_fmt_t(s['reported_med'])} | "
                f"{s['done']}/{s['n']} | {s['true_pct']:.1f}% | {s['overlap']:.1f}% | {s['idle']:.0f} min |")

    lines += [
        "",
        "## Message loss sweep",
        "",
        "Clear-skies mission with more and more of every message lost. Median time to mission complete.",
        "",
        "| Message loss | " + " | ".join(STRATEGIES[s].label for s in ("vanta", "central")) + " |",
        "|---|---|---|",
    ]
    for p in losses:
        cells = []
        for st in ("vanta", "central"):
            s = _summarise([r for r in rows if r["scenario"] == f"loss{int(p * 100)}" and r["strategy"] == st])
            cells.append(f"{_fmt_t(s['reported_med'])} ({s['done']}/{s['n']})")
        lines.append(f"| {p:.0%} | " + " | ".join(cells) + " |")

    text = "\n".join(lines) + "\n"
    if out:
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(text, encoding="utf-8")
    return text
